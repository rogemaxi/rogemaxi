// Localization tooling.
//   node tools/i18n.mjs keys <scope…>        → print [key, english] JSON for scopes (section ids, lab.N, unit.N, bank, ui)
//   node tools/i18n.mjs merge                → rebuild src/data/i18n/content/<lang>.json from src/data/i18n/content/<lang>/*.json
//   node tools/i18n.mjs report [--json]      → completeness per language (UI + content), written to docs/TRANSLATION_REPORT.md
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { contentKeys } from '../src/app/i18nkeys.js';
import { allScopes } from './scopes.mjs';

const root = new URL('../', import.meta.url).pathname;
const LANGS = ['es', 'fr', 'ht', 'pt', 'ar', 'zh', 'hi', 'bn', 'vi', 'ko', 'ja'];
const [cmd, ...args] = process.argv.slice(2);

if (cmd === 'keys') {
  const scopes = await allScopes();
  const out = {};
  for (const a of args) {
    const sc = scopes.filter(s => s.scope === a || (a.endsWith('*') && s.scope.startsWith(a.slice(0, -1))));
    for (const s of sc) for (const [k, v] of contentKeys(s.scope, s.obj)) out[k] = v;
  }
  console.log(JSON.stringify(out, null, 1));
}

if (cmd === 'merge') {
  for (const l of LANGS) {
    const dir = `${root}src/data/i18n/content/${l}`;
    const merged = {};
    if (existsSync(dir)) for (const f of readdirSync(dir).filter(f => f.endsWith('.json')).sort()) Object.assign(merged, JSON.parse(readFileSync(`${dir}/${f}`, 'utf8')));
    writeFileSync(`${root}src/data/i18n/content/${l}.json`, JSON.stringify(merged));
    console.log(l, Object.keys(merged).length, 'keys');
  }
}

if (cmd === 'report') {
  const scopes = await allScopes();
  const keys = new Map();
  for (const s of scopes) for (const [k, v] of contentKeys(s.scope, s.obj)) keys.set(k, { v, group: s.group });
  const ui = JSON.parse(readFileSync(`${root}src/data/i18n/ui/en.json`, 'utf8'));
  const groups = [...new Set([...keys.values()].map(k => k.group))];
  const rows = [];
  for (const l of LANGS) {
    const pack = JSON.parse(readFileSync(`${root}src/data/i18n/content/${l}.json`, 'utf8'));
    const uipack = JSON.parse(readFileSync(`${root}src/data/i18n/ui/${l}.json`, 'utf8'));
    const uiDone = Object.keys(ui).filter(k => uipack[k]).length;
    const per = {};
    for (const g of groups) {
      const ks = [...keys].filter(([, x]) => x.group === g);
      per[g] = [ks.filter(([k]) => pack[k]).length, ks.length];
    }
    const stale = Object.keys(pack).filter(k => !keys.has(k)).length;
    const total = [...keys.keys()].filter(k => pack[k]).length;
    rows.push({ lang: l, ui: [uiDone, Object.keys(ui).length], content: [total, keys.size], per, stale });
  }
  if (args.includes('--json')) { console.log(JSON.stringify(rows, null, 1)); process.exit(0); }
  const pct = ([a, b]) => (b ? `${a}/${b} (${(100 * a / b).toFixed(1)}%)` : '—');
  let md = `# Translation Completeness Report\n\nGenerated by \`node tools/i18n.mjs report\` on ${new Date().toISOString().slice(0, 10)}.\n\n` +
    `A language is **complete** only when 100% of UI strings and 100% of instructional content keys are translated. ` +
    `Untranslated strings fall back to English in the app, are marked \`lang="en"\`, and are counted here.\n\n` +
    `All translations in this build were drafted with AI assistance. None has yet been reviewed by a native-speaker teacher; ` +
    `treat every language as **unreviewed** until a reviewer signs off in docs/TRANSLATION_REVIEW.md.\n\n` +
    `English source keys: ${keys.size} content, ${Object.keys(ui).length} UI.\n\n| Language | UI | Content (all) | ${groups.join(' | ')} | Stale keys | Status |\n|---|---|---|${groups.map(() => '---').join('|')}|---|---|\n`;
  for (const r of rows) {
    const complete = r.ui[0] === r.ui[1] && r.content[0] === r.content[1];
    md += `| ${r.lang} | ${pct(r.ui)} | ${pct(r.content)} | ${groups.map(g => pct(r.per[g])).join(' | ')} | ${r.stale} | ${complete ? 'COMPLETE (unreviewed)' : 'INCOMPLETE'} |\n`;
  }
  mkdirSync(`${root}docs`, { recursive: true });
  writeFileSync(`${root}docs/TRANSLATION_REPORT.md`, md);
  console.log(md);
}
